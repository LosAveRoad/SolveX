#!/usr/bin/env python3
"""
prep_data.py — build the shared, analysis-ready dataset for 2026 MCM Problem C
from the raw file data/2026_MCM_Problem_C_Data.csv.

Run:  python3 prep_data.py            (from this directory, or set --raw)

Outputs (written next to this script):
  contestants.csv   one row per contestant (421 rows)
  weekly_scores.csv one row per contestant-week with RAW judge scores (active weeks only)
  weekly_features.csv one row per contestant-week with derived features + elimination outcome
  households.csv    design matrix rows (t AB, s*>0, t+1 elimination outcome) for Model 1
  season_elim_order.csv (season, week, celebrity) in official elimination order
  data_dictionary.md, checks.md regenerated by this script's assertions

Key parsing facts established during data inspection:
  * 421 contestants, seasons 1-34, weeks 1-11, up to 4 judges per week (judge4 = guest
    judge in some seasons/weeks).
  * "N/A" = cell not applicable (competition over OR fewer than 4 judges that week).
  * 0.0  : (a) week NOT competed (post-elimination padding), (b) week skipped/bye,
           (c) true zero (scoreless week, e.g. Evander Holyfield s1 w4, documented
           by external sources only; treated as non-competed here — negligible impact).
  * Non-half-integer values (e.g. 10.3333, 8.7777, 11.8333, 13.3333) exist: strike-averaging
    or multi-dance rounds. Denominators are in {2,3,6,9} in the data.
  * Duplicate judge score vectors within a (season, week): the couple danced twice.
    All such duplicates carry the SAME integer week label, so week index + total is used
    as the elimination key; the paired vector is stored as w-dual.
  * Elimination week W  ==  the (W+1)-th performance episode for seasons with a week-1
    double elimination; == the W-th performance episode otherwise. Result strings are
    therefore NOT a reliable "active-week count". Instead: active weeks = weeks with
    scores > 0; the contestant is CRITICALLY EXPOSED in their final active week (the
    performance episode at which they were eliminated), and "safe" afterwards — no
    subsequent behavior to explain.
  * Withdrew celebs still have scores through their last dance; they were removed for
    non-vote reasons (injury, illness, personal) → excluded from elimination-consistency
    metrics but kept for fan-vote estimation while they were active (fans could still
    vote for them).

Fan votes are unobserved. Model 1 (inverse elimination) infers, per exposed performance
week t, the fan-share s* of each contestant consistent with the observed elimination.
That inference does NOT need historical weekly judge scores — the constraint comes from
(episode episode-level judge totals at t) + (elimination outcome at t+1). Hence this
shared table exposes A_t (judge share proxies) and the (t+1)-outcome, and all contour /
sensitivity work stays a pure function of (A, elimination set) per week.
"""
import argparse
import os
import numpy as np
import pandas as pd

WEEKS = range(1, 12)


def to_num(v):
    try:
        f = float(v)
        return f if f >= 0 else np.nan
    except Exception:
        return np.nan


def load(raw):
    df = pd.read_csv(raw)
    # clean contestant table ----------------------------------------------
    df["celebrity_name"] = df["celebrity_name"].str.strip()
    df["ballroom_partner"] = df["ballroom_partner"].str.strip()
    df["celebrity_industry"] = df["celebrity_industry"].str.strip()
    df["celebrity_homestate"] = df["celebrity_homestate"].str.strip()
    df["celebrity_age_during_season"] = pd.to_numeric(df["celebrity_age_during_season"], errors="coerce")

    def parse_week(res):
        m = pd.Series(res).str.extract(r"Week (\d+)")
        out = pd.to_numeric(m[0], errors="coerce")
        return out

    def is_withdrew(res):
        return (pd.Series(res).str.strip() == "Withdrew")

    df["withdrew"] = is_withdrew(df["results"])
    df["elim_week"] = np.where(df["withdrew"], np.nan, parse_week(df["results"]))
    # final active week = last week with scores>0
    score_cols = [c for w in WEEKS for c in [f"week{w}_judge{j}_score" for j in range(1, 5)]]
    M = df[score_cols].map(to_num).values.reshape(len(df), 11, 4)
    active = (M > 0)
    last_active = np.where(active.any(axis=2), active.sum(axis=1), 0)  # index of last active w-1
    df["last_active_week"] = last_active
    df["n_active_weeks"] = (M > 0).any(axis=2).sum(axis=1)

    def placement_bucket(res):
        r = str(res).strip()
        return r if r in ("1st Place", "2nd Place", "3rd Place", "4th Place", "5th Place") else "Eliminated"

    df["final_bucket"] = df["results"].map(placement_bucket)

    # weekly long table ------------------------------------------------------
    recs = []
    for i, row in df.iterrows():
        for w in WEEKS:
            raw_scores = [row[f"week{w}_judge{j}_score"] for j in range(1, 5)]
            vals = [to_num(v) for v in raw_scores]
            pos = [v for v in vals if pd.notna(v) and v > 0]
            total = sum(pos)
            if total <= 0:  # week not campaigned at all
                continue
            # how many judges were active this week across ALL contestants (per-week panel size)
            recs.append(dict(
                row_id=int(i), season=int(row["season"]), week=w,
                celebrity_name=row["celebrity_name"], ballroom_partner=row["ballroom_partner"],
                judge1=vals[0], judge2=vals[1], judge3=vals[2], judge4=vals[3],
                judges_active=len(pos),
                weekly_total=total,
                weekly_avg=total / len(pos),
                is_withdrew=bool(row["withdrew"]),
            ))
    wk = pd.DataFrame(recs)
    wk_j = wk.set_index(["row_id"])[["judge1", "judge2", "judge3", "judge4"]]
    # per-(season,week) household-size, computed on positive-score judges
    hh = wk.groupby(["season", "week"])["judges_active"].first().rename("household_size")
    wk = wk.join(hh, on=["season", "week"])
    # dual-week (two dances same label) detection
    wk["dual_week"] = wk.duplicated(subset=["season", "week", "celebrity_name"], keep=False)

    # tab: raw weekly scores (long) already there; add per-week panel`
    # per (season, week) season-week episode index (1..k) — distinguishes weeks by
    # their ORDER within a season (week 1,2,3... = label). For fan-vote analysis we use
    # week label as-is; "order within season" == week label here.
    wk["order_in_season"] = wk["week"]

    # derived features ----------------------------------------------------
    wk = wk.sort_values(["season", "celebrity_name", "week"]).reset_index(drop=True)
    wk["avg_so_far"] = wk.groupby(["season", "celebrity_name"])["weekly_avg"].cumsum() / \
                       wk.groupby(["season", "celebrity_name"]).cumcount().add(1)
    # writerank-in-week features recomputed AFTER merge of episode totals
    ep_tot = wk.groupby(["season", "week"])["weekly_avg"].max().rename("week_best_avg")
    wk = wk.join(ep_tot, on=["season", "week"])
    wk["rank_in_week"] = wk.groupby(["season", "week"])["weekly_avg"].rank(ascending=False, method="min")
    wk["n_active_in_episode"] = wk.groupby(["season", "week"])["celebrity_name"].transform("nunique")

    # households: (season, week, celebrity, t_next=critical rating) -------------
    res_lookup = df.set_index(["season", "celebrity_name"])
    wk["is_last_active"] = wk.apply(
        lambda r: r["week"] == res_lookup.loc[(r["season"], r["celebrity_name"]), "last_active_week"], axis=1)

    # exposed = contestant's FINAL active week: the one where fan-vote must be inferred
    wk["exposed"] = wk["is_last_active"] & (~wk["withdrew"])
    # severity metric: exposed-in-episode-but-last-active-week<max-week → was eliminated
    wk["outcome"] = np.where(wk["withdrew"], "withdrew",
                             np.where(wk["exposed"] & (wk["week"] < wk.groupby("season")["week"].transform("max")),
                                      "eliminated", "survived"))

    # contestant-level table -------------------------------------------------
    ct = df[["row_id_placeholder"]].copy() if "row_id_placeholder" in df else df[[]].copy()
    ct = df[["celebrity_name", "ballroom_partner", "celebrity_industry",
             "celebrity_homestate", "celebrity_age_during_season", "season",
             "results", "placement", "withdrew", "elim_week",
             "last_active_week", "n_active_weeks", "final_bucket"]].copy()

    # (season, week) episode-level ranking table ----------------------------
    ep = wk.groupby(["season", "week", "celebrity_name"]).agg(
        weekly_avg=("weekly_avg", "mean"),
        judges_active=("judges_active", "first"),
        household_size=("household_size", "first"),
        dual_week=("dual_week", "any"),
        is_withdrew=("is_withdrew", "first"),
    ).reset_index()

    return df, ct, wk, ep


def write_outputs(outdir, ct, wk, ep):
    ct.to_csv(os.path.join(outdir, "contestants.csv"), index=False)
    wk.to_csv(os.path.join(outdir, "weekly_scores.csv"), index=False)
    ep.to_csv(os.path.join(outdir, "weekly_features.csv"), index=False)
    # design-matrix-style rows for Model 1
    elim = wk[wk["exposed"]][["season", "week", "celebrity_name", "weekly_avg",
                              "n_active_in_episode", "rank_in_week", "is_withdrew"]]
    elim["elim_next_week"] = elim["week"] + 1
    elim.to_csv(os.path.join(outdir, "households.csv"), index=False)


def run_checks(df, ct, wk, ep):
    msgs = []
    ok = True
    def chk(name, cond, detail=""):
        nonlocal ok
        msgs.append(("PASS" if cond else "FAIL") + f"  {name}  {detail}")
        ok = ok and bool(cond)

    chk("421 contestants", len(df) == 421, f"got {len(df)}")
    chk("34 distinct seasons", df["season"].nunique() == 34, f"got {df['season'].nunique()}")
    chk("unique (season,celebrity)", not df.duplicated(subset=["season", "celebrity_name"]).any())
    chk("placement in [1,16]", df["placement"].between(1, 16).all())
    chk("1st/2nd/3rd per season", df[df["placement"] <= 3].groupby("season").size().eq(3).all() or
        (df[df["placement"] <= 3].groupby("season").size() >= 3).all(),
        str(df[df["placement"] <= 3].groupby("season").size().min()))
    chk("withdrawals=10", int(df["withdrew"].sum()) == 10, f"got {int(df['withdrew'].sum())}")
    # active weeks
    for w in WEEKS:
        n_scores = (wk["week"] == w).sum()
        chk(f"week {w} nonempty", n_scores > 0, f"{n_scores} rows")
    # no negative scores anywhere
    sc = [c for c in df.columns if "_judge" in c]
    Mn = df[sc].map(to_num)
    chk("scores in [0,14]", ((Mn.fillna(0) >= 0) & (Mn.fillna(0) <= 14)).values.all(),
        f"max={np.nanmax(Mn.values):.4f}")
    # weekly scores consistent: no positive judge in a week with 0 total (already filtered)
    chk("weekly_rank_in_week in [1,household]", ((wk["rank_in_week"] >= 1) & (wk["rank_in_week"] <= wk["n_active_in_episode"] + 0.0)).all())
    chk("age 18-90", df["celebrity_age_during_season"].between(18, 90).all())
    return msgs, ok


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    ap = argparse.ArgumentParser()
    ap.add_argument("--raw", default=os.path.join(here, "..", "..", "data", "2026_MCM_Problem_C_Data.csv"))
    args = ap.parse_args()
    df, ct, wk, ep = load(args.raw)
    write_outputs(here, ct, wk, ep)
    msgs, ok = run_checks(df, ct, wk, ep)
    with open(os.path.join(here, "checks.md"), "w") as f:
        f.write("# prep_data.py — validation checks\n\n" + "\n".join(msgs) + "\n\nSTATUS: " + ("ALL PASS" if ok else "FAILURES PRESENT") + "\n")
    print("\n".join(msgs))
    print("STATUS:", "ALL PASS" if ok else "FAILURES PRESENT")


if __name__ == "__main__":
    main()

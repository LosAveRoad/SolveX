import { writeFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";
import { summarizeArtifacts, hasRealArtifacts } from "./artifacts.js";

/**
 * B2/E4 + ADR-0009 兜底摘要。
 *
 * 旧实现无论目录里有什么都写 "⚠ Not available."，把模型真实产出的 CSV 数值全部抹掉，
 * 下游 P3/P4 因此误判「计算未完成」。现在先扫描目录：如果有真实产物，就把文件清单与
 * CSV 数值摘要写进兜底摘要，明确标注来源为自动扫描而非模型自述，绝不编造结论。
 */
export function ensureSummary(modelDir: string, modelName: string): string {
  const evidence = summarizeArtifacts(modelDir);
  const hasData = hasRealArtifacts(modelDir);
  const body = [
    `# ${modelName} Results Summary (auto-generated from workspace scan)`, "",
    "## Status",
    hasData
      ? "⚠ The agent did not write results_summary.md. Real data/code artifacts WERE produced; " +
        "the numbers below are read directly from those files by SolveX, not invented."
      : "⚠ The agent did not write results_summary.md and no data artifacts were found.",
    "",
    "## Key Numerical Results",
    hasData
      ? "Derived from generated CSV files (see artifact scan below); inspect the files for full precision."
      : "⚠ Not available — no data files were generated.",
    "",
    "## Sanity Checks",
    "⚠ NOT PERFORMED by the agent — downstream stages must verify these numbers.", "",
    "## Model Parameters",
    "See the generated .py files listed below.", "",
    "## Data Files Generated",
    evidence, "",
    "## Figures",
    /\.png|\.jpe?g|\.svg|\.pdf/i.test(evidence)
      ? "See figures listed in the artifact scan above."
      : "⚠ No image files found in this model directory.",
    "",
    "## Issues or Limitations",
    "This summary was generated by SolveX because the agent did not write results_summary.md. " +
    "Figures and agent-side validation may be missing; treat extracted numbers as unverified.",
    "",
  ].join("\n");
  mkdirSync(modelDir, { recursive: true });
  writeFileSync(join(modelDir, "results_summary.md"), body);
  return body;
}
